"""Performance Driver (k6).

Menghasilkan skrip k6 dari Registry (hanya endpoint aman/GET), menjalankan 4 profil beban
(Typical, Peak, Stress, Spike), memonitor penggunaan CPU & memori kontainer/host secara real-time,
mengekspor ringkasan metrik k6 (RPS, latensi P95/P99, error rate), dan menghitung Pperf
(Platency, Presource, Pperf) yang siap dikonsumsi oleh Scorecard Engine.
"""

from __future__ import annotations

import csv
import json
import logging
import math
import os
import re
import shutil
import subprocess
import sys
import threading
import time
from datetime import datetime
from pathlib import Path
from typing import Any, Callable

import httpx

from audit.schemas import Registry, Route
from audit.scorecard.engine import L_LATENCY_THRESHOLD_MS, compute_pperf, aggregate_pperf

logger = logging.getLogger("audit.performance")


def find_k6() -> str | None:
    """Mencari binary k6 di PATH atau lokasi instalasi standar host."""
    env_k6 = os.environ.get("K6_BIN")
    if env_k6 and Path(env_k6).exists():
        return env_k6

    found = shutil.which("k6")
    if found:
        return found

    # Lokasi umum pada Windows
    windows_candidates = [
        r"C:\k6-v1.5.0-windows-amd64\k6.exe",
        r"C:\Program Files\k6\k6.exe",
        r"C:\ProgramData\chocolatey\bin\k6.exe",
    ]
    for cand in windows_candidates:
        if Path(cand).exists():
            return cand

    return None


def _is_safe_route(route: Route) -> bool:
    """Menentukan apakah route aman untuk uji beban (tidak destruktif)."""
    method = route.method.upper()
    path = route.path.lower()

    # Hindari endpoint autentikasi pengubahan password, hapus, checkout berbayar
    risky_keywords = ["delete", "logout", "change-password", "drop", "reset", "basket/checkout"]
    if any(k in path for k in risky_keywords):
        return False

    if method == "GET":
        return True

    # Izinkan POST pencarian atau registrasi feedback dummy yang aman
    if method == "POST" and ("search" in path or "feedback" in path or "captcha" in path):
        return True

    return False


def generate_k6_script(
    registry: Registry,
    out_path: str | Path,
    target_url: str | None = None,
    auth_header: str | None = None,
) -> Path:
    """Menghasilkan skrip k6 (JavaScript ES6) berdasarkan endpoint aman dari Registry."""
    out_file = Path(out_path)
    out_file.parent.mkdir(parents=True, exist_ok=True)

    base_url = (target_url or registry.target_url).rstrip("/")
    header_val = auth_header or registry.auth_header or ""

    endpoints: list[dict[str, Any]] = []

    for r in registry.routes:
        if not _is_safe_route(r):
            continue

        method = r.method.upper()
        path = r.path

        # Ganti placeholder path param seperti {id} menjadi nilai aman default
        path = re.sub(r"\{[a-zA-Z0-9_]+\}", "1", path)

        query = ""
        if "search" in path.lower():
            query = "q=apple"
        elif "order" in path.lower():
            query = "id=1"

        body = ""
        if method == "POST":
            if "search" in path.lower():
                body = json.dumps({"query": "apple"})
            elif "feedback" in path.lower():
                body = json.dumps({"comment": "Test load query", "rating": 5})

        endpoints.append({
            "method": method,
            "path": path,
            "query": query,
            "body": body,
        })

    # Jika tidak ada endpoint aman terdeteksi, tambahkan fallback standar
    if not endpoints:
        endpoints.append({"method": "GET", "path": "/", "query": "", "body": ""})

    js_template = f"""// Generated by audit-cli Performance Driver
import http from 'k6/http';
import {{ check, sleep }} from 'k6';

export const options = {{
  discardResponseBodies: true,
  thresholds: {{
    http_req_failed: ['rate<0.05'], // peringatan jika error rate > 5%
  }},
}};

const TARGET_URL = __ENV.TARGET_URL || "{base_url}";
const AUTH_HEADER = __ENV.AUTH_HEADER || "{header_val}";

const ENDPOINTS = {json.dumps(endpoints, indent=2)};

export default function () {{
  const ep = ENDPOINTS[Math.floor(Math.random() * ENDPOINTS.length)];
  let url = TARGET_URL + ep.path;
  if (ep.query) {{
    url += (url.includes('?') ? '&' : '?') + ep.query;
  }}

  const params = {{
    headers: {{
      'User-Agent': 'audit-cli-k6/1.0',
    }},
    tags: {{ name: ep.path }},
  }};

  if (AUTH_HEADER) {{
    params.headers['Authorization'] = AUTH_HEADER;
  }}

  let res;
  if (ep.method === 'GET') {{
    res = http.get(url, params);
  }} else if (ep.method === 'POST') {{
    params.headers['Content-Type'] = 'application/json';
    res = http.post(url, ep.body || '{{}}', params);
  }} else {{
    res = http.get(url, params);
  }}

  check(res, {{
    'status is 2xx or 3xx': (r) => r.status >= 200 && r.status < 400,
  }});

  // Random sleep 50ms - 150ms untuk simulasi jeda user yang realistis
  sleep(0.05 + Math.random() * 0.1);
}}
"""

    out_file.write_text(js_template, encoding="utf-8")
    logger.info(f"[Performance Driver] Skrip k6 disimpan di: {out_file} ({len(endpoints)} endpoint aktif)")
    return out_file


class ResourceMonitor:
    """Memonitor CPU dan memori secara real-time via Docker stats atau fallback Host psutil."""

    def __init__(
        self,
        container_name: str | None = "juice-shop",
        interval: float = 2.0,
        reference_cores: float = 2.0,
        reference_mem_bytes: float = 2.0 * 1024 * 1024 * 1024,  # 2 GB acuan
    ) -> None:
        self.container_name = container_name
        self.interval = interval
        self.reference_cores = reference_cores
        self.reference_mem_bytes = reference_mem_bytes
        self.samples: list[dict[str, Any]] = []
        self._stop_event = threading.Event()
        self._thread: threading.Thread | None = None
        self.source = "none"

    def _sample_docker(self) -> tuple[float, float] | None:
        if not self.container_name:
            return None
        try:
            cmd = ["docker", "stats", "--no-stream", "--format", "{{json .}}", self.container_name]
            res = subprocess.run(cmd, capture_output=True, text=True, timeout=3.0)
            if res.returncode == 0 and res.stdout.strip():
                data = json.loads(res.stdout.strip().splitlines()[0])
                # CPU format: "12.34%"
                raw_cpu_str = data.get("CPUPerc", "0%").rstrip("%")
                raw_cpu = float(raw_cpu_str) if raw_cpu_str else 0.0

                # Normalisasikan terhadap acuan 2 core target
                # Jika docker stats melaporkan 100% per core, CPU dibagi acuan 2 core
                norm_cpu = raw_cpu / self.reference_cores

                # Mem format: "123.4MiB / 2GiB"
                mem_usage_str = data.get("MemUsage", "")
                mem_bytes = 0.0
                if "/" in mem_usage_str:
                    used_str = mem_usage_str.split("/")[0].strip()
                    mem_bytes = self._parse_bytes(used_str)
                    norm_mem = (mem_bytes / self.reference_mem_bytes) * 100.0
                else:
                    norm_mem = float(data.get("MemPerc", "0%").rstrip("%"))

                self.source = "docker"
                return norm_cpu, norm_mem
        except Exception:
            pass
        return None

    def _sample_host(self) -> tuple[float, float]:
        try:
            import psutil
            cpu = float(psutil.cpu_percent(interval=None))
            mem = float(psutil.virtual_memory().percent)
            self.source = "host_psutil"
            return cpu, mem
        except Exception:
            self.source = "fallback_zero"
            return 0.0, 0.0

    @staticmethod
    def _parse_bytes(val_str: str) -> float:
        """Konversi string ukuran memori (cth: 150MiB, 1.2GiB, 500kB) ke bytes."""
        val_str = val_str.strip()
        units = {
            "b": 1,
            "kb": 1000, "kib": 1024,
            "mb": 1000 ** 2, "mib": 1024 ** 2,
            "gb": 1000 ** 3, "gib": 1024 ** 3,
        }
        match = re.match(r"^([0-9.]+)\s*([a-zA-Z]+)?$", val_str)
        if not match:
            return 0.0
        num = float(match.group(1))
        unit = (match.group(2) or "b").lower()
        return num * units.get(unit, 1)

    def _monitor_loop(self) -> None:
        while not self._stop_event.is_set():
            t_now = time.time()
            sample = self._sample_docker()
            if sample is None:
                sample = self._sample_host()

            cpu, mem = sample
            self.samples.append({
                "timestamp": t_now,
                "cpu_pct": round(max(0.0, min(100.0, cpu)), 2),
                "mem_pct": round(max(0.0, min(100.0, mem)), 2),
                "source": self.source,
            })
            self._stop_event.wait(self.interval)

    def start(self) -> None:
        self.samples.clear()
        self._stop_event.clear()
        self._thread = threading.Thread(target=self._monitor_loop, daemon=True)
        self._thread.start()

    def stop(self) -> None:
        if self._thread and self._thread.is_alive():
            self._stop_event.set()
            self._thread.join(timeout=3.0)

    def save_csv(self, out_path: Path) -> None:
        out_path.parent.mkdir(parents=True, exist_ok=True)
        with open(out_path, "w", newline="", encoding="utf-8") as f:
            writer = csv.DictWriter(f, fieldnames=["timestamp", "cpu_pct", "mem_pct", "source"])
            writer.writeheader()
            writer.writerows(self.samples)

    def get_summary(self) -> dict[str, float]:
        if not self.samples:
            return {
                "cpu_pct_avg": 0.0,
                "cpu_pct_peak": 0.0,
                "mem_pct_avg": 0.0,
                "mem_pct_peak": 0.0,
            }

        cpu_vals = [s["cpu_pct"] for s in self.samples]
        mem_vals = [s["mem_pct"] for s in self.samples]

        return {
            "cpu_pct_avg": round(sum(cpu_vals) / len(cpu_vals), 2),
            "cpu_pct_peak": round(max(cpu_vals), 2),
            "mem_pct_avg": round(sum(mem_vals) / len(mem_vals), 2),
            "mem_pct_peak": round(max(mem_vals), 2),
        }


def restart_target_container(container_name: str | None, target_url: str, timeout: int = 30) -> bool:
    """Me-restart container target dan melakukan polling healthcheck hingga siap."""
    if not container_name:
        return True

    logger.info(f"[Performance Driver] Me-restart container target '{container_name}'...")
    try:
        res = subprocess.run(["docker", "restart", container_name], capture_output=True, timeout=timeout)
        if res.returncode != 0:
            logger.warning(f"[Performance Driver] Gagal restart docker container: {res.stderr.decode().strip()}")
            return False
    except Exception as exc:
        logger.warning(f"[Performance Driver] Docker tidak dapat diakses untuk restart container: {exc}")
        return False

    # Polling target healthcheck
    t_start = time.time()
    logger.info(f"[Performance Driver] Menunggu kesiapan target API di {target_url}...")
    while time.time() - t_start < timeout:
        try:
            r = httpx.get(target_url, timeout=1.5)
            if r.status_code < 500:
                logger.info(f"[Performance Driver] Target siap (HTTP {r.status_code})")
                return True
        except Exception:
            time.sleep(1.0)

    logger.warning(f"[Performance Driver] Target tidak merespons setelah {timeout}s polling pasca-restart.")
    return False


def parse_k6_summary(
    summary_data: dict[str, Any],
    resource_summary: dict[str, float] | None = None,
    L: float = L_LATENCY_THRESHOLD_MS,
) -> dict[str, Any]:
    """Mengekstrak metrik kunci dari file summary JSON k6 dan menghitung Pperf."""
    metrics = summary_data.get("metrics", {})

    def _extract_metric(name: str, key: str, default: float = 0.0) -> float:
        m = metrics.get(name, {})
        if isinstance(m, dict):
            # Cek values dict terlebih dahulu, lalu root dict
            v_dict = m.get("values", m)
            if isinstance(v_dict, dict) and key in v_dict:
                return float(v_dict[key])
        return default

    total_requests = int(_extract_metric("http_reqs", "count", 0))
    rps = round(_extract_metric("http_reqs", "rate", 0.0), 2)

    latency_avg = round(_extract_metric("http_req_duration", "avg", 0.0), 2)
    latency_min = round(_extract_metric("http_req_duration", "min", 0.0), 2)
    latency_med = round(_extract_metric("http_req_duration", "med", 0.0), 2)
    latency_max = round(_extract_metric("http_req_duration", "max", 0.0), 2)
    latency_p90 = round(_extract_metric("http_req_duration", "p(90)", 0.0), 2)
    latency_p95 = round(_extract_metric("http_req_duration", "p(95)", 0.0), 2)
    latency_p99 = round(_extract_metric("http_req_duration", "p(99)", latency_p95), 2)

    # Error rate dari http_req_failed atau checks
    error_rate = _extract_metric("http_req_failed", "rate", 0.0)
    if error_rate == 0.0 and "checks" in metrics:
        ch = metrics.get("checks", {}).get("values", {})
        c_fails = float(ch.get("fails", 0))
        c_passes = float(ch.get("passes", 0))
        if (c_passes + c_fails) > 0:
            error_rate = c_fails / (c_passes + c_fails)

    res_stats = resource_summary or {
        "cpu_pct_avg": 0.0,
        "cpu_pct_peak": 0.0,
        "mem_pct_avg": 0.0,
        "mem_pct_peak": 0.0,
    }

    profile_raw = {
        "total_requests": total_requests,
        "rps": rps,
        "latency_avg_ms": latency_avg,
        "latency_min_ms": latency_min,
        "latency_med_ms": latency_med,
        "latency_max_ms": latency_max,
        "latency_p90_ms": latency_p90,
        "latency_p95_ms": latency_p95,
        "latency_p99_ms": latency_p99,
        "error_rate": round(error_rate, 4),
        "cpu_pct_avg": res_stats.get("cpu_pct_avg", 0.0),
        "cpu_pct_peak": res_stats.get("cpu_pct_peak", 0.0),
        "mem_pct_avg": res_stats.get("mem_pct_avg", 0.0),
        "mem_pct_peak": res_stats.get("mem_pct_peak", 0.0),
    }

    # Hitung Pperf, Platency, Presource
    score, breakdown = compute_pperf(profile_raw, L=L)
    profile_raw["scorecard"] = breakdown
    profile_raw["pperf"] = score

    return profile_raw


def run_k6_profile(
    profile_name: str,
    script_path: Path,
    out_dir: Path,
    target_url: str,
    container_name: str | None = "juice-shop",
    scale: float = 1.0,
    quick: bool = False,
    progress_callback: Callable[[str], None] | None = None,
) -> dict[str, Any]:
    """Menjalankan satu profil pengujian performa k6."""
    k6_bin = find_k6()
    if not k6_bin:
        raise FileNotFoundError("k6 executable tidak ditemukan di host.")

    # Reset container dan tunggu kesiapan target
    restart_target_container(container_name, target_url)

    # Konfigurasi parameter profil
    # Sesuai proposal:
    # - typical: 100 VU, durasi 5m
    # - peak: 500 VU, durasi 5m
    # - stress: 1000 VU, durasi 5m
    # - spike: 1 -> 1000 VU dalam 1s, tahan 2m
    scale = max(0.01, scale)
    vus = max(1, int(100 * scale))
    duration_s = 300 if not quick else 20

    is_spike = (profile_name.lower() == "spike")
    if profile_name.lower() == "peak":
        vus = max(1, int(500 * scale))
        duration_s = 300 if not quick else 20
    elif profile_name.lower() == "stress":
        vus = max(1, int(1000 * scale))
        duration_s = 300 if not quick else 30
    elif is_spike:
        vus = max(1, int(1000 * scale))
        duration_s = 120 if not quick else 20

    summary_file = out_dir / f"k6_{profile_name}.json"
    res_csv_file = out_dir / f"resource_stats_{profile_name}.csv"

    cmd = [
        k6_bin,
        "run",
        "--summary-export", str(summary_file),
        "--summary-trend-stats", "avg,min,med,max,p(90),p(95),p(99)",
        "--quiet",
    ]

    if is_spike:
        # Ramp 1 -> target VU dalam 1s, tahan duration_s, rampdown 5s
        cmd.extend([
            "--stage", f"1s:{vus}",
            "--stage", f"{duration_s}s:{vus}",
            "--stage", "5s:0",
        ])
    else:
        cmd.extend([
            "--vus", str(vus),
            "--duration", f"{duration_s}s",
        ])

    cmd.append(str(script_path))

    env = os.environ.copy()
    env["TARGET_URL"] = target_url

    msg = f"Menjalankan profil '{profile_name.upper()}': {vus} VU, durasi ~{duration_s}s..."
    logger.info(f"[Performance Driver] {msg}")
    if progress_callback:
        progress_callback(msg)

    # Jalankan monitor sumber daya
    monitor = ResourceMonitor(container_name=container_name, interval=2.0)
    monitor.start()

    try:
        proc = subprocess.run(
            cmd,
            env=env,
            capture_output=True,
            text=True,
            timeout=duration_s + 60,
        )
        if proc.returncode != 0:
            logger.warning(f"[Performance Driver] k6 exit with code {proc.returncode}: {proc.stderr}")
    except subprocess.TimeoutExpired:
        logger.error(f"[Performance Driver] k6 execution timed out untuk profil {profile_name}")
    finally:
        monitor.stop()
        monitor.save_csv(res_csv_file)

    # Parse hasil
    summary_data: dict[str, Any] = {}
    if summary_file.exists():
        try:
            summary_data = json.loads(summary_file.read_text(encoding="utf-8"))
        except Exception as exc:
            logger.error(f"[Performance Driver] Gagal membaca {summary_file}: {exc}")

    res_summary = monitor.get_summary()
    profile_result = parse_k6_summary(summary_data, resource_summary=res_summary)
    profile_result["profile"] = profile_name
    profile_result["target_vus"] = vus
    profile_result["configured_duration_s"] = duration_s

    return profile_result


def run_performance(
    registry: Registry,
    run_dir: str | Path,
    profiles: list[str] | None = None,
    scale: float = 1.0,
    quick: bool = False,
    container_name: str | None = "juice-shop",
    target_url: str | None = None,
    auth_header: str | None = None,
    progress_callback: Callable[[str], None] | None = None,
) -> dict[str, Any]:
    """Menjalankan seluruh rangkaian uji performa k6 dan menyimpan performance.json."""
    out_dir = Path(run_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    out_json = out_dir / "performance.json"

    target = target_url or registry.target_url
    selected_profiles = profiles or ["typical", "peak", "stress", "spike"]

    # 1. Cek keberadaan binary k6
    k6_bin = find_k6()
    if not k6_bin:
        err_msg = (
            "k6 executable tidak ditemukan di host. "
            "Silakan pasang k6 dari https://k6.io atau definisikan environment variable K6_BIN."
        )
        logger.warning(f"[Performance Driver] {err_msg}")
        result_err = {
            "error": err_msg,
            "status": "SKIPPED",
            "evaluated": False,
            "target_url": target,
            "timestamp": datetime.now().isoformat(),
            "profiles": {},
            "aggregate_pperf": 0.0,
        }
        out_json.write_text(json.dumps(result_err, indent=2), encoding="utf-8")
        return result_err

    # 2. Generate k6 script
    script_path = out_dir / "k6_test_script.js"
    generate_k6_script(
        registry=registry,
        out_path=script_path,
        target_url=target,
        auth_header=auth_header,
    )

    # 3. Eksekusi per profil
    profile_results: dict[str, dict[str, Any]] = {}
    for prof in selected_profiles:
        try:
            res = run_k6_profile(
                profile_name=prof,
                script_path=script_path,
                out_dir=out_dir,
                target_url=target,
                container_name=container_name,
                scale=scale,
                quick=quick,
                progress_callback=progress_callback,
            )
            profile_results[prof] = res
        except Exception as exc:
            logger.error(f"[Performance Driver] Gagal mengeksekusi profil {prof}: {exc}")
            profile_results[prof] = {
                "profile": prof,
                "error": str(exc),
                "pperf": 0.0,
                "latency_avg_ms": 9999.0,
                "error_rate": 1.0,
            }

    # 4. Agregasi Pperf
    final_pperf, breakdowns = aggregate_pperf(profile_results)

    final_payload = {
        "timestamp": datetime.now().isoformat(),
        "target_url": target,
        "scale": scale,
        "quick": quick,
        "container_name": container_name,
        "profiles": profile_results,
        "aggregate_pperf": final_pperf,
        "breakdowns": breakdowns,
        "evaluated": True,
        "status": "COMPLETED",
    }

    out_json.write_text(json.dumps(final_payload, indent=2), encoding="utf-8")
    logger.info(f"[Performance Driver] Hasil pengujian performa disimpan di: {out_json} (Pperf={final_pperf})")
    return final_payload
